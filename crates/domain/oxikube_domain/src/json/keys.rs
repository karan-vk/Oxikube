//! The key dictionary: the object keys Kubernetes objects repeat, stored as a small number in a
//! [`JsonDoc`](super::JsonDoc) instead of their text.
//!
//! A pod has about 150 keys and nearly all of them come from this list (`metadata`, `containers`,
//! `lastTransitionTime`, ...), so a key costs one byte instead of a heap `String` and its text. A key
//! not in the list (a label, an annotation, a CRD field) is stored inline, byte for byte.
//!
//! The list is part of the encoding but not of any stored data: documents are never persisted, so
//! it can grow or be reordered freely. Ids are positions in [`KEYS`]; the most frequent keys come
//! first so they fit the one-byte form of a varint (ids below 127).

