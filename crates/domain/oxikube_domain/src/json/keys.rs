/// The inline marker: the key text follows.
pub(super) const INLINE: u64 = 0;

/// `(key, code)` pairs sorted by key, built on first use.
fn index() -> &'static [(&'static str, u16)] {
    static INDEX: OnceLock<Vec<(&'static str, u16)>> = OnceLock::new();
    INDEX.get_or_init(|| {
        let mut index: Vec<(&'static str, u16)> = KEYS
            .iter()
            .enumerate()
            .map(|(i, key)| (*key, u16::try_from(i + 1).unwrap_or(u16::MAX)))
            .collect();
        // A key listed twice keeps its first (more frequent) position.
        index.sort_by(|a, b| a.0.cmp(b.0).then(a.1.cmp(&b.1)));
        index.dedup_by(|later, earlier| later.0 == earlier.0);
        index
    })
}

/// The code of `key` (`1..`), or `None` when it is not in the dictionary.
pub(super) fn code_of(key: &str) -> Option<u64> {
    let index = index();
    index
        .binary_search_by(|(k, _)| (*k).cmp(key))
        .ok()
        .map(|at| u64::from(index[at].1))
}

/// The key a code (`1..`) stands for.
pub(super) fn key_of(code: u64) -> Option<&'static str> {
    let at = usize::try_from(code.checked_sub(1)?).ok()?;
    KEYS.get(at).copied()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_key_round_trips_through_its_code() {
        for key in KEYS {
            let code = code_of(key).expect("listed keys have a code");
            assert_eq!(key_of(code), Some(*key));
        }
    }

    #[test]
    fn unknown_keys_have_no_code() {
        assert_eq!(code_of("not-a-kubernetes-key"), None);
        assert_eq!(key_of(0), None);
        assert_eq!(key_of(KEYS.len() as u64 + 1), None);
    }

    #[test]
    fn the_hot_keys_fit_one_varint_byte() {
        for key in ["name", "metadata", "spec", "status", "labels", "containers"] {
            assert!(code_of(key).unwrap() < 128, "{key}");
        }
    }
}
