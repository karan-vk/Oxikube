/// Fields that only mean something in the cluster they were read from: removed in
/// [`SanitizeMode::Copy`](super::SanitizeMode::Copy) only. Owner UIDs point at objects that do not
/// exist in the target, and a finalizer nobody there handles would block deletion.
pub(super) const COPY_GLOBAL: &[&[&str]] = &[
    &["metadata", "ownerReferences"],
    &["metadata", "finalizers"],
];

/// One per-kind strip, for [`SanitizeMode::Copy`](super::SanitizeMode::Copy).
pub(super) struct KindStrip {
    /// API group of the kind (`""` for core).
    pub group: &'static str,
    /// Kind.
    pub kind: &'static str,
    /// What to remove.
    pub path: &'static [&'static str],
    /// When this returns true for the whole object the row is skipped.
    pub keep_when: Option<fn(&Value) -> bool>,
}

/// A headless Service (`clusterIP: None`) is a choice, not an allocation: keep it.
fn headless(object: &Value) -> bool {
    object.pointer("/spec/clusterIP").and_then(Value::as_str) == Some("None")
}

/// A Job that chose its own selector (`manualSelector: true`) keeps it.
fn manual_selector(object: &Value) -> bool {
    object.pointer("/spec/manualSelector") == Some(&Value::Bool(true))
}

