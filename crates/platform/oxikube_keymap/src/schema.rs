//! The JSON schema for the user's `keymap.json`.
//!
//! The shape is Zed's keymap file: a list of sections `{ context, use_key_equivalents,
//! bindings }`, where a binding maps keystrokes to `null` (unbind), an action name, or
//! `[name, data]`. The action names are the ones the [`ActionRegistry`] holds, the same table
//! the commands, the palette and the validator use, so the schema never lists an action the
//! keymap would reject.
//!
//! Two sources, one function ([`keymap_schema`]):
//! - the checked-in `keymap.schema.json` is built from the actions linked into the app binary
//!   ([`ActionRegistry::from_inventory`]) by `oxikube --print-keymap-schema`; `cargo xtask
//!   gen-keymap-schema` writes it and `--check` (CI) fails when it is stale. Output is
//!   canonical (keys sorted), so it depends only on the registered actions and contexts.
//! - the editor builds one at run time from the live registry
//!   ([`ActionRegistry::from_app`]), so actions an extension registers appear too.

use serde_json::{Value, json};

use crate::known::KnownNames;
use crate::registry::ActionRegistry;

/// The schema for a keymap whose actions are `actions` and whose context names are `known`
/// (offered as examples; a `context` is an expression, so it is not an enum).
pub fn keymap_schema(actions: &ActionRegistry, known: &KnownNames) -> Value {
    let names: Vec<&str> = actions.names().collect();
    let contexts: Vec<&str> = known.contexts().collect();
    json!({
        "$schema": "https://json-schema.org/draft/2019-09/schema",
        "title": "Oxikube keymap.json",
        "description": "User key bindings for Oxikube. Generated by `cargo xtask gen-keymap-schema`; do not edit.",
        "type": "array",
        "items": { "$ref": "#/$defs/Section" },
        "allowTrailingCommas": true,
        "$defs": {
            "ActionName": {
                "description": "A registered action, `namespace::Name`. Every declared command is also an action of the same name.",
                "type": "string",
                "enum": names,
            },
            "Binding": {
                "description": "What the keystrokes do: an action name, `[name, data]` for an action that takes data, or null to unbind the keystrokes in this context.",
                "oneOf": [
                    { "type": "null" },
                    { "$ref": "#/$defs/ActionName" },
                    {
                        "type": "array",
                        "prefixItems": [{ "$ref": "#/$defs/ActionName" }, {}],
                        "minItems": 1,
                        "maxItems": 2,
                    },
                ],
            },
            "Section": {
                "description": "Bindings that share a context. Sections apply in file order; the later binding of a key wins.",
                "type": "object",
                "additionalProperties": false,
                "properties": {
                    "context": {
                        "description": "Where the bindings are active: a key-context expression such as `ResourceTable && !Editing`. Absent means everywhere.",
                        "type": "string",
                        "examples": contexts,
                    },
                    "use_key_equivalents": {
                        "description": "Make shortcuts follow the key's character on non-US layouts instead of its position.",
                        "type": "boolean",
                    },
                    "bindings": {
                        "description": "Keystrokes (`ctrl-k ctrl-s` is a two-keystroke sequence) to what they do.",
                        "type": "object",
                        "additionalProperties": { "$ref": "#/$defs/Binding" },
                    },
                },
            },
        },
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_action_enum_is_the_registry() {
        let actions = ActionRegistry::from_names(["table::SelectNext", "palette::Toggle"]);
        let schema = keymap_schema(&actions, &KnownNames::of(["Workspace"], []));
        assert_eq!(
            schema["$defs"]["ActionName"]["enum"],
            json!(["palette::Toggle", "table::SelectNext"])
        );
        assert_eq!(
            schema["$defs"]["Section"]["properties"]["context"]["examples"],
            json!(["Workspace"])
        );
        assert_eq!(schema["type"], "array");
    }

    #[test]
    fn the_schema_is_deterministic() {
        let actions = ActionRegistry::from_names(["b::B", "a::A", "b::A"]);
        let known = KnownNames::of(["Z", "A"], ["f"]);
        assert_eq!(
            keymap_schema(&actions, &known),
            keymap_schema(&actions, &known)
        );
    }
}
