/// The title shown for `action`: the title of the command it is or stands for.
fn title_of(action: &str) -> String {
    if let Some(meta) = ActionRegistry::command(action) {
        return meta.title.to_owned();
    }
    ActionRegistry::commands_of(action)
        .first()
        .and_then(|id| ActionRegistry::command(id.as_str()))
        .map(|meta| meta.title.to_owned())
        .unwrap_or_default()
}

/// Escape `text` for a markdown table cell.
fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}

fn action_cell(action: &KeymapAction) -> (String, String) {
    match action {
        KeymapAction::Unbind => ("*unbound*".to_owned(), String::new()),
        KeymapAction::Action { name, data } => {
            let shown = match data {
                Some(data) => format!("`{name}` `{data}`"),
                None => format!("`{name}`"),
            };
            (cell(&shown), cell(&title_of(name)))
        }
    }
}

/// The text of `docs/keymap.md`.
///
/// # Panics
///
/// Panics when an embedded keymap does not parse; a unit test keeps that from shipping.
pub fn keymap_markdown() -> String {
    let mut out = String::from(
        "<!-- Generated by `cargo xtask gen-keymap-docs`; do not edit. -->\n\
         # Oxikube key bindings\n\n\
         This file is generated from the keymaps embedded in the app\n\
         (`crates/platform/oxikube_assets/assets/keymaps/`) and the command titles. CI fails when\n\
         it is stale: run `cargo xtask gen-keymap-docs` after changing a keymap or a command title.\n\n\
         Layers, weakest first: the default keymap of your OS, the base keymap chosen with the\n\
         `base_keymap` setting (`default`, `k9s` or `vim`), then your own `keymap.json`, which wins.\n\
         Switching `base_keymap` takes effect at once and never rewrites `keymap.json`. Within a\n\
         layer a later binding beats an earlier one, and `null` unbinds a key of a weaker layer.\n\n",
    );
    for doc in documents() {
        write_document(&mut out, &doc);
    }
    out
}

fn write_document(out: &mut String, doc: &Doc) {
    let parsed = parse_keymap(doc.text, doc.layer).expect("embedded keymap parses");
    let _ = write!(out, "## {}\n\n`{}`. {}\n\n", doc.title, doc.file, doc.intro);
    let mut contexts: Vec<(String, Vec<(String, KeymapAction)>)> = Vec::new();
    for (_, section) in &parsed.sections {
        let context = section.context_expr().unwrap_or("").to_owned();
        let index = match contexts.iter().position(|(name, _)| *name == context) {
            Some(index) => index,
            None => {
                contexts.push((context, Vec::new()));
                contexts.len() - 1
            }
        };
        for (keys, value) in &section.bindings {
            if let Ok(action) = KeymapAction::from_json(value) {
                contexts[index].1.push((keys.clone(), action));
            }
        }
    }
    for (context, bindings) in contexts {
        let heading = if context.is_empty() {
            "Everywhere".to_owned()
        } else {
            format!("`{}`", cell(&context))
        };
        let _ = write!(
            out,
            "### {heading}\n\n| Keys | Action | Does |\n| --- | --- | --- |\n"
        );
        for (keys, action) in bindings {
            let (action, title) = action_cell(&action);
            let _ = writeln!(out, "| `{}` | {action} | {title} |", cell(&keys));
        }
        out.push('\n');
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_embedded_keymap_has_a_table_and_the_text_is_deterministic() {
        let text = keymap_markdown();
        assert_eq!(text, keymap_markdown());
        for doc in documents() {
            assert!(
                text.contains(&format!("## {}\n", doc.title)),
                "{}",
                doc.title
            );
        }
        assert!(text.starts_with("<!-- Generated by"));
        assert!(text.contains("| `g g` | `resource_table::SelectFirst` |"));
        assert!(text.contains("| `c` | `resource_table::CopyName` |"));
    }

    #[test]
    fn pipes_in_a_cell_are_escaped() {
        assert_eq!(cell("a|b"), "a\\|b");
    }
}
