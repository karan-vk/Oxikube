//! `docs/keymap.md`: the key table generated from the embedded keymaps (E21-S09).
//!
//! The text is a pure function of the embedded JSON files and the command titles, so
//! `cargo xtask gen-keymap-docs --check` can compare it byte for byte with the checked-in file.
//! Contexts and bindings keep the order of their file (that order is the precedence the keymap
//! itself uses), and a context that appears in several sections of one file becomes one table.

use std::fmt::Write as _;

use oxikube_assets::KeymapPlatform;

use crate::file::{KeymapAction, parse_keymap};
use crate::layer::KeymapLayer;
use crate::registry::ActionRegistry;

/// Where the generated file lives, relative to the workspace root.
pub const KEYMAP_DOCS_PATH: &str = "docs/keymap.md";

/// One keymap the document describes.
struct Doc {
    title: &'static str,
    file: &'static str,
    layer: KeymapLayer,
    text: &'static str,
    intro: &'static str,
}

